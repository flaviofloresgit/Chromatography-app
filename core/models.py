"""
Data models for Chromatography GC-MS Analysis.
Completely decoupled from any frontend/UI framework.
"""

from dataclasses import dataclass, field, asdict
from typing import List, Dict, Optional, Any
from datetime import date, datetime


@dataclass
class SampleMetadata:
    """Metadata describing the chromatographic run and sample."""
    sample_name: str
    sample_code: str = ""
    analysis_date: str = field(default_factory=lambda: date.today().isoformat())
    column_type: str = "Elite-5MS (30m x 0.25mm x 0.25µm, 5% diphenyl 95% dimethylpolysiloxane)"
    carrier_gas: str = "Helium"
    flow_rate: str = "1.0 mL/min"
    inlet_temperature: str = "250 °C"
    oven_program: str = "40 °C (1 min) -> 10 °C/min -> 280 °C (5 min)"
    split_ratio: str = "20:1"
    operator: str = ""
    notes: str = ""
    original_file_name: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class IonPeak:
    """Single mass spectrum ion."""
    mz: float
    signal: float
    relative_intensity: float = 0.0  # normalized to 100% or 1000


@dataclass
class MassSpectrum:
    """Mass spectrum data for an integrated chromatographic peak."""
    peak_id: int
    ions: List[IonPeak] = field(default_factory=list)
    base_peak_mz: float = 0.0
    base_peak_signal: float = 0.0

    @property
    def top_ions(self) -> List[IonPeak]:
        """Returns the top 10 most abundant ions."""
        return sorted(self.ions, key=lambda x: x.signal, reverse=True)[:10]

    def get_prominent_mz_list(self, top_n: int = 5) -> List[int]:
        """Returns list of rounded m/z values of most abundant ions."""
        return [int(round(ion.mz)) for ion in self.top_ions[:top_n]]


@dataclass
class PeakData:
    """Single chromatographic peak with retention time, area and mass spectrum."""
    peak_id: int
    rt: float
    area: float
    relative_area_pct: float = 0.0
    spectrum: Optional[MassSpectrum] = None

    def to_dict(self) -> Dict[str, Any]:
        d = {
            "peak_id": self.peak_id,
            "rt": round(self.rt, 3),
            "area": self.area,
            "relative_area_pct": round(self.relative_area_pct, 2)
        }
        if self.spectrum:
            d["base_peak_mz"] = self.spectrum.base_peak_mz
            d["top_ions"] = self.spectrum.get_prominent_mz_list(5)
        return d


@dataclass
class ChromatogramPoint:
    """Single data point in the Total Ion Chromatogram (TIC)."""
    rt: float
    signal: float


@dataclass
class NistCandidate:
    """Hit from NIST Mass Spectral Library search."""
    name: str
    formula: str = ""
    mw: float = 0.0
    cas: str = ""
    similarity_score: float = 0.0  # 0.0 to 100.0%
    base_peak: float = 0.0


@dataclass
class IdentificationResult:
    """Final compound identification generated by Gemini AI & NIST spectral matching."""
    peak_id: int
    rt: float
    area: float
    relative_area_pct: float
    compound_name: str
    iupac_name: str = ""
    cas_number: str = ""
    formula: str = ""
    molecular_weight: float = 0.0
    confidence_level: str = "Medium"  # "High", "Medium", "Low"
    confidence_score: float = 0.0     # 0.0 to 100.0%
    nist_similarity: float = 0.0      # 0.0 to 100.0%
    identification_source: str = "Gemini AI + NIST Library"
    chemical_family: str = ""
    retention_behavior_analysis: str = ""
    fragmentation_rationale: str = ""
    key_ions: List[int] = field(default_factory=list)
    alternative_candidates: List[Dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class SampleAnalysis:
    """Complete analysis state for a sample."""
    sample_id: str
    metadata: SampleMetadata
    chromatogram: List[ChromatogramPoint] = field(default_factory=list)
    peaks: List[PeakData] = field(default_factory=list)
    identifications: List[IdentificationResult] = field(default_factory=list)
    total_area: float = 0.0
    summary_ai: str = ""
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())

    def get_peak_by_id(self, peak_id: int) -> Optional[PeakData]:
        for p in self.peaks:
            if p.peak_id == peak_id:
                return p
        return None

    def get_identification_by_peak_id(self, peak_id: int) -> Optional[IdentificationResult]:
        for ident in self.identifications:
            if ident.peak_id == peak_id:
                return ident
        return None
